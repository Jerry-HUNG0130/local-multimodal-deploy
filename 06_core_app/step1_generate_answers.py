def main():
    print("🤖 正在讓受測者 (本地 LLM 模型) 進行作答...")
    results = []
    
    for case in test_cases:
        q = case["question"]
        print(f"  👉 測試問題: {q}")
        try:
            response = requests.post(API_URL, json={"question": q}, timeout=60)
            response.raise_for_status()
            response_data = response.json()
            
            ans = response_data.get("answer", "")
            ctx = response_data.get("context_used", "")
            
            case_result = {
                "question": q,
                "ground_truth": case["ground_truth"],
                "answer": ans,
                "context": ctx
            }
            results.append(case_result)
        except Exception as e:
            print(f"  ❌ API 呼叫失敗: {e}")
            return

    output_file = "evaluation_data.json"
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=4)
        
    print(f"\n✅ 已將 {len(results)} 筆作答結果儲存至 {output_file}")

if __name__ == "__main__":
    main()
